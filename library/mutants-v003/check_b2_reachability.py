"""API witness and model-prerequisite checks. Native reachability needs CheckB2 mode."""
import json,random,tempfile
from pathlib import Path
from urllib.parse import urlsplit,parse_qs
from verify import witness
from replay import replay

def signature(rows):
    users={};books={};holds={};steps=[]
    for r in rows:
        p=urlsplit(r.get('path') or r['url']);parts=p.path.strip('/').split('/');entity=parts[0];method=r['method'];body=r['input'] or {};step={'method':method,'entity':entity}
        if method=='POST' and entity in ['users','books']:
            ids=users if entity=='users' else books;ids[r['response']['id']]=len(ids);step['slot']=len(ids)-1
        elif method=='POST':
            step.update(user=users[int(body['userId'])],book=books[int(body['bookId'])])
            if entity=='holds':holds[r['response']['id']]=len(holds);step['slot']=len(holds)-1
        elif method=='DELETE' and entity=='loans':step.update(user=users[int(parts[1])],book=books[int(parts[2])])
        elif method=='DELETE' and entity=='holds':step['slot']=holds[int(parts[1])]
        elif method=='DELETE' and entity=='books':step['slot']=books[int(parts[1])]
        elif method=='GET' and entity=='loans':
            q=parse_qs(p.query);step.update(user=users[int(q['userId'][0])],book=books[int(q['bookId'][0])])
        else:raise ValueError('Unexpected diagnostic step')
        steps.append(step)
    return steps

def check_rows(rows):
    expected=json.loads(Path(__file__).with_name('b2-plan.json').read_text())
    if signature(rows)!=expected:raise ValueError('B2 witness semantic sequence differs')
    with tempfile.TemporaryDirectory() as d:
        results={mode:replay(rows,mode,Path(d)/(mode+'.jsonl'),42)['status'] for mode in ['original','baseline','B2']}
    if results!={'original':'PASS','baseline':'PASS','B2':'DIFFERENT'}:raise ValueError(results)
    return {'requests':len(rows),'users':3,'books':3,'api_replays':results,'native_context_reachability':'verified only when generated by native CheckB2 mode'}

if __name__=='__main__':
    random.seed(42);rows=witness('B2','original')
    for i,r in enumerate(rows,1):r.update(url='http://127.0.0.1'+r['path'],role='tool',order=i)
    print(json.dumps(check_rows(rows),indent=2))
